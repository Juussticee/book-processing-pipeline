"""Redaction of credentials from log records, URLs and error text.

Secrets must never reach ``logs/app.log``, the console, or exception
strings that get persisted. The helpers here are deliberately
dependency-free so they can be used from anywhere in the pipeline,
including inside ``core.logger``.

Two layers of protection are used by the application:

1. :func:`redact` / :func:`redact_url` at call sites that echo a URL or
   an exception.
2. :class:`SecretRedactingFilter` installed on every log handler, which
   catches anything that slipped through, including exception text
   generated by ``requests`` (``raise_for_status`` embeds the full URL).
"""

from __future__ import annotations

import logging
import re
from typing import Any, List, Tuple

#: Placeholder substituted for a removed credential.
REDACTED = "***REDACTED***"

# Query-string style credentials: ``?key=...``, ``&access_token=...``
_QUERY_PARAM_NAMES = (
    "api_key",
    "apikey",
    "api-key",
    "access_token",
    "refresh_token",
    "auth_token",
    "client_secret",
    "client_id",
    "password",
    "secret",
    "sig",
    "signature",
    "token",
    "key",
)

_QUERY_PATTERN = re.compile(
    r"(?P<prefix>[?&](?:" + "|".join(_QUERY_PARAM_NAMES) + r")=)"
    r"(?P<value>[^&\s\"'<>\\]+)",
    re.IGNORECASE,
)

# Dict/JSON-ish representations: ``'key': 'abc'``, ``"api_key": "abc"``
_MAPPING_PATTERN = re.compile(
    r"(?P<prefix>[\"'](?:"
    + "|".join(_QUERY_PARAM_NAMES)
    + r")[\"']\s*:\s*[\"'])(?P<value>[^\"']*)(?P<suffix>[\"'])",
    re.IGNORECASE,
)

# Well-known token shapes.
_TOKEN_PATTERNS: List[Tuple[re.Pattern, str]] = [
    # Google API keys (AIza + 35 chars)
    (re.compile(r"AIza[0-9A-Za-z_\-]{10,}"), REDACTED),
    # OpenAI-style keys
    (re.compile(r"\bsk-[A-Za-z0-9_\-]{16,}"), REDACTED),
    # Authorization: Bearer <token>
    (
        re.compile(r"(?P<prefix>Bearer\s+)[A-Za-z0-9._\-+/=]{8,}", re.IGNORECASE),
        r"\g<prefix>" + REDACTED,
    ),
]


def redact(text: Any) -> str:
    """Return ``text`` with any credential-looking fragment masked.

    Non-string input is converted with :func:`str` so this can be used
    directly on exception objects.
    """
    if text is None:
        return ""
    result = text if isinstance(text, str) else str(text)

    for pattern, replacement in _TOKEN_PATTERNS:
        result = pattern.sub(replacement, result)

    result = _QUERY_PATTERN.sub(
        lambda m: m.group("prefix") + REDACTED,
        result,
    )
    result = _MAPPING_PATTERN.sub(
        lambda m: m.group("prefix") + REDACTED + m.group("suffix"),
        result,
    )
    return result


def redact_url(url: Any) -> str:
    """Redact credentials embedded in a URL (or any URL-bearing text)."""
    return redact(url)


class SecretRedactingFilter(logging.Filter):
    """Logging filter that strips credentials from messages and arguments.

    The record is rewritten so formatted output (including tracebacks'
    message line) contains no secrets. Attach to ``handler`` objects so
    it applies to every logger writing through that handler.
    """

    def filter(self, record: logging.LogRecord) -> bool:  # noqa: A003
        try:
            if record.args:
                # ``%``-style templates: redact after interpolation so the
                # secret cannot hide inside an argument.
                try:
                    message = record.getMessage()
                except Exception:
                    message = str(record.msg)
                record.msg = redact(message)
                record.args = ()
            else:
                record.msg = redact(record.msg)
        except Exception:  # pragma: no cover - never break logging
            pass
        return True
